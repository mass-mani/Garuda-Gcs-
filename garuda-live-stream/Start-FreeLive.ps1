param([int]$Port = 8787)
$ErrorActionPreference = 'Stop'
$Project = $PSScriptRoot
$State = Join-Path $Project '.local'
New-Item -ItemType Directory -Force $State | Out-Null
if (Test-Path (Join-Path $State 'processes.json')) {
    throw 'A previous launch exists. Run Stop-FreeLive.ps1 first.'
}
$Node = (Get-Command node.exe -ErrorAction Stop).Source
$Cloudflared = Join-Path $State 'cloudflared.exe'
if (!(Test-Path $Cloudflared)) {
    Write-Host 'Downloading Cloudflare Tunnel from its official release...'
    $Release = Invoke-RestMethod 'https://api.github.com/repos/cloudflare/cloudflared/releases/latest'
    $Asset = $Release.assets | Where-Object name -eq 'cloudflared-windows-amd64.exe' | Select-Object -First 1
    if (!$Asset -or !$Asset.digest -or !$Asset.digest.StartsWith('sha256:')) { throw 'No checksum-verified Windows release available.' }
    Invoke-WebRequest $Asset.browser_download_url -OutFile $Cloudflared
    if ((Get-FileHash $Cloudflared -Algorithm SHA256).Hash.ToLower() -ne $Asset.digest.Substring(7)) { throw 'Cloudflared checksum mismatch.' }
}
Push-Location (Join-Path $Project 'signaling')
try { & npm.cmd ci --omit=dev; if ($LASTEXITCODE) { throw 'Dependency installation failed.' } } finally { Pop-Location }
$TunnelLog = Join-Path $State 'tunnel.stderr.log'
$Tunnel = Start-Process $Cloudflared -ArgumentList @('tunnel','--url',"http://127.0.0.1:$Port",'--no-autoupdate') -WindowStyle Hidden -PassThru -RedirectStandardError $TunnelLog -RedirectStandardOutput (Join-Path $State 'tunnel.stdout.log')
$Server = $null
try {
    $Deadline = (Get-Date).AddSeconds(60)
    $PublicUrl = $null
    while ((Get-Date) -lt $Deadline) {
        if ($Tunnel.HasExited) { throw 'Tunnel stopped. See .local/tunnel.stderr.log.' }
        $LogText = Get-Content $TunnelLog -Raw -ErrorAction SilentlyContinue
        if ($LogText -match 'https://[a-z0-9-]+\.trycloudflare\.com') { $PublicUrl = $Matches[0]; break }
        Start-Sleep -Milliseconds 500
    }
    if (!$PublicUrl) { throw 'Tunnel did not return a public HTTPS URL within 60 seconds.' }
    $SecretBytes = New-Object byte[] 32
    $Rng = [Security.Cryptography.RandomNumberGenerator]::Create()
    $Rng.GetBytes($SecretBytes)
    $Rng.Dispose()
    $Token = [Convert]::ToBase64String($SecretBytes)
    $Names = @('PORT','BIND_HOST','PUBLIC_BASE_URL','PUBLISHER_TOKEN','TRUST_PROXY')
    $Saved = @{}
    foreach ($Name in $Names) { $Saved[$Name] = [Environment]::GetEnvironmentVariable($Name,'Process') }
    try {
        $env:PORT = "$Port"
        $env:BIND_HOST = '127.0.0.1'
        $env:PUBLIC_BASE_URL = $PublicUrl
        $env:PUBLISHER_TOKEN = $Token
        $env:TRUST_PROXY = '1'
        $Server = Start-Process $Node -ArgumentList 'server.js' -WorkingDirectory (Join-Path $Project 'signaling') -WindowStyle Hidden -PassThru -RedirectStandardError (Join-Path $State 'server.stderr.log') -RedirectStandardOutput (Join-Path $State 'server.stdout.log')
    } finally {
        foreach ($Name in $Names) { [Environment]::SetEnvironmentVariable($Name,$Saved[$Name],'Process') }
    }
    $Healthy = $false
    for ($Attempt = 0; $Attempt -lt 30; $Attempt++) {
        if ($Server.HasExited) { throw 'Signaling server stopped. See .local/server.stderr.log.' }
        try { $Healthy = (Invoke-RestMethod "http://127.0.0.1:$Port/healthz").ok; if ($Healthy) { break } } catch { }
        Start-Sleep -Milliseconds 300
    }
    if (!$Healthy) { throw 'Local signaling server failed its health check.' }
    @{
        serverId=$Server.Id; serverStarted=$Server.StartTime.ToUniversalTime().ToString('o')
        tunnelId=$Tunnel.Id; tunnelStarted=$Tunnel.StartTime.ToUniversalTime().ToString('o')
        url=$PublicUrl
    } | ConvertTo-Json | Set-Content (Join-Path $State 'processes.json')
    $ConnectionFile = Join-Path $State 'G12-connection.txt'
    @("GARUDA LIVE - enter these in the Android app", "Server URL: $PublicUrl", "Publisher token: $Token", '', 'Keep this token private. Share only the viewer link generated by the app.', 'Keep this PC on. Run Stop-FreeLive.ps1 to stop the free server and tunnel.') | Set-Content $ConnectionFile
    Write-Host "Free HTTPS signaling started: $PublicUrl"
    Write-Host "G12 setup details saved to: $ConnectionFile"
    Write-Host 'The temporary hostname changes on restart. No uptime guarantee; video still uses WebRTC directly.'
} catch {
    if ($Server -and !$Server.HasExited) { Stop-Process -Id $Server.Id }
    if (!$Tunnel.HasExited) { Stop-Process -Id $Tunnel.Id }
    throw
}
